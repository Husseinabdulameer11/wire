/* embed - turn a text file into a C string constant.
 *
 *   embed input.html name > output.h
 *
 * Writes `static const char name[] = "...";` as many short literals, which
 * the compiler joins together. Used to build build/wire_view.h. */
#include <stdio.h>

int main(int argc, char **argv)
{
    FILE *f;
    int c, col = 0;
    if (argc != 3) { fprintf(stderr, "usage: embed input name > output.h\n"); return 2; }
    f = fopen(argv[1], "rb");
    if (!f) { perror(argv[1]); return 1; }
    printf("/* Generated by tools/embed from %s - do not edit. */\n", argv[1]);
    printf("static const char %s[] =\n\"", argv[2]);
    while ((c = fgetc(f)) != EOF) {
        if (c == '\r') continue;
        if (c == '\\' || c == '"') printf("\\%c", c);
        else if (c == '\n') { printf("\\n\"\n\""); col = 0; continue; }
        else if (c == '?') printf("\\?"); /* no trigraphs */
        else if (c < 32 || c > 126) printf("\\%03o", c);
        else putchar(c);
        if (++col > 200) { printf("\"\n\""); col = 0; }
    }
    printf("\";\n");
    fclose(f);
    return 0;
}
