/* embed - turn a text file into a C string constant.
 *
 *   embed input.html name > output.h
 *
 * Writes `static const char name[] = "...";` as many short literals, which
 * the compiler joins together. Used to build build/wire_view.h.
 *
 * A line that is exactly `//@include file` is replaced by that file (found
 * next to the input), so the page can keep its simulator in its own
 * source file, src/wire_sim.js, which the tests also load. */
#include <stdio.h>
#include <string.h>

static int col = 0;

static void put(int c)
{
    if (c == '\r') return;
    if (c == '\\' || c == '"') printf("\\%c", c);
    else if (c == '\n') { printf("\\n\"\n\""); col = 0; return; }
    else if (c == '?') printf("\\?"); /* no trigraphs */
    else if (c < 32 || c > 126) printf("\\%03o", c);
    else putchar(c);
    if (++col > 200) { printf("\"\n\""); col = 0; }
}

static int copy(const char *path, int depth)
{
    static const char tag[] = "//@include ";
    char line[4096], dir[1024];
    const char *slash;
    FILE *f = fopen(path, "rb");
    if (!f) { perror(path); return 1; }
    slash = strrchr(path, '/');
    if (!slash) slash = strrchr(path, '\\');
    if (slash && (size_t)(slash - path) < sizeof dir - 1) {
        memcpy(dir, path, (size_t)(slash - path + 1));
        dir[slash - path + 1] = 0;
    } else dir[0] = 0;
    while (fgets(line, sizeof line, f)) {
        size_t n = strlen(line);
        if (depth < 4 && strncmp(line, tag, sizeof tag - 1) == 0) {
            char inc[2048];
            while (n && (line[n - 1] == '\n' || line[n - 1] == '\r' || line[n - 1] == ' ')) line[--n] = 0;
            if (strlen(dir) + strlen(line + sizeof tag - 1) >= sizeof inc) { fprintf(stderr, "embed: path too long\n"); fclose(f); return 1; }
            strcpy(inc, dir);
            strcat(inc, line + sizeof tag - 1);
            if (copy(inc, depth + 1)) { fclose(f); return 1; }
            continue;
        }
        { size_t i; for (i = 0; i < n; i++) put((unsigned char)line[i]); }
    }
    fclose(f);
    return 0;
}

int main(int argc, char **argv)
{
    if (argc != 3) { fprintf(stderr, "usage: embed input name > output.h\n"); return 2; }
    printf("/* Generated by tools/embed from %s - do not edit. */\n", argv[1]);
    printf("static const char %s[] =\n\"", argv[2]);
    if (copy(argv[1], 0)) return 1;
    printf("\";\n");
    return 0;
}
